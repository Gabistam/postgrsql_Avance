-- (tournois et inscriptions sont créées pendant les exercices N2)
DROP TABLE IF EXISTS inscriptions, tournois, joueurs, matchs, equipes, genres, parties, streams CASCADE;

-- ---------- SPORT : un mini-championnat de 6 équipes ----------
CREATE TABLE equipes (
    id    INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nom   VARCHAR(50) NOT NULL UNIQUE,
    ville VARCHAR(50) NOT NULL
);

CREATE TABLE joueurs (
    id        INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nom       VARCHAR(80) NOT NULL,
    equipe_id INTEGER REFERENCES equipes(id),      -- NULL = joueur sans club
    poste     VARCHAR(20) NOT NULL,
    buts      INTEGER NOT NULL DEFAULT 0 CHECK (buts >= 0)
);

CREATE TABLE matchs (
    id             INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    journee        INTEGER NOT NULL,
    equipe_dom_id  INTEGER NOT NULL REFERENCES equipes(id),
    equipe_ext_id  INTEGER NOT NULL REFERENCES equipes(id),
    buts_dom       INTEGER NOT NULL CHECK (buts_dom >= 0),
    buts_ext       INTEGER NOT NULL CHECK (buts_ext >= 0)
);

