-- ---------- Contrôle : chaque table doit afficher le bon nombre de lignes ----------
SELECT 'equipes' AS table_name, COUNT(*) AS lignes FROM equipes
UNION ALL SELECT 'joueurs', COUNT(*) FROM joueurs
UNION ALL SELECT 'matchs',  COUNT(*) FROM matchs
UNION ALL SELECT 'genres',  COUNT(*) FROM genres
UNION ALL SELECT 'streams', COUNT(*) FROM streams
UNION ALL SELECT 'parties', COUNT(*) FROM parties;
